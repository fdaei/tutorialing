def run(text: str, *, bold: bool = False, size: int = 24) -> str:
    props = [
        '<w:rtl/>',
        f'<w:sz w:val="{size}"/><w:szCs w:val="{size}"/>',
        '<w:rFonts w:ascii="Noto Naskh Arabic" w:hAnsi="Noto Naskh Arabic" '
        'w:cs="Noto Naskh Arabic"/>',
    ]
    if bold:
        props.append('<w:b/><w:bCs/>')
    return f'<w:r><w:rPr>{"".join(props)}</w:rPr><w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def paragraph(text: str = "", *, heading: bool = False, title: bool = False,
              bullet: bool = False, center: bool = False) -> str:
    alignment = "center" if (title or center) else "right"
    spacing_after = 160 if heading else 100
    indent = '<w:ind w:right="420"/>' if bullet else ""
    ppr = (
        '<w:pPr><w:bidi/>'
        f'<w:jc w:val="{alignment}"/><w:spacing w:after="{spacing_after}" w:line="360" w:lineRule="auto"/>'
        f'{indent}</w:pPr>'
    )
    prefix = "• " if bullet else ""
    size = 34 if title else (28 if heading else 24)
    return f'<w:p>{ppr}{run(prefix + text, bold=(heading or title), size=size)}</w:p>'


def page_break() -> str:
    return '<w:p><w:r><w:br w:type="page"/></w:r></w:p>'


